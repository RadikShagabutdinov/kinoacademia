  brand: 'clamp(11px, 0.78vw, 15px)',
  /** «Рейтинги» — заголовок экрана. */
  title: 'clamp(32px, 3.1vw, 60px)',
  /** Часы. */
  clock: 'clamp(24px, 2.3vw, 44px)',
  /** «Персонажи» / «Компании» — заголовки колонок. */
  boardTitle: 'clamp(18px, 1.56vw, 30px)',
