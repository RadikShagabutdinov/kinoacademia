/**
 * Стабильные ключи для строк-скелетонов.
 *
 * Индекс массива в качестве key React не любит, а у плейсхолдеров нет своего id.
 * Набор фиксированных строк снимает вопрос и не мешает переупорядочиванию:
 * скелетоны живут ровно до прихода данных и никогда не пересортировываются.
 */
export const skeletonKeys = (count: number): string[] =>
  Array.from({ length: count }, (_, i) => `skeleton-${i}`);
